const capture = require('./capture.cjs');
// Isolated hidden Electron UI regression; native dialogs are test doubles.
const { _electron: electron } = require('playwright');
const { expect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

async function main() {
  const root = path.resolve(__dirname, '..'), output = path.join(root, 'artifacts');
  fs.mkdirSync(output, { recursive: true });
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'desk-v2-ux-'));
  const report = { startedAt: new Date().toISOString(), data, assertions: [], errors: [] };
  let app;
  try {
    app = await electron.launch({ executablePath: path.join(root, 'out/Application Desk V2-win32-x64/ApplicationDesk.exe'), env: { ...process.env, DESK_DATA_HOME: data, DESK_SHOW_WINDOW: '0' } });
    const page = await app.firstWindow(); page.setDefaultTimeout(10000);
    page.on('pageerror', e => report.errors.push(e.message));
    await page.getByLabel('目标入学年份', { exact: true }).selectOption('custom');
    await page.getByLabel('自定义入学年份').fill('2038');
    await page.getByLabel('入学月份（可选）', { exact: true }).selectOption('9');
    await page.getByLabel('搜索城市或时区').fill('上海');
    await page.getByLabel('个人时区').selectOption('Asia/Shanghai');
    await page.getByRole('button', { name: /建立个人工作区/ }).click();
    await page.getByRole('button', { name: '添加目标项目', exact: true }).click();
    let modal = page.getByRole('dialog', { name: '添加一个目标项目', exact: true });
    await modal.getByLabel('学校名称').fill('UCL');
    await modal.getByLabel('项目名称').fill('QA Learning Design');
    await modal.getByLabel('学位层次', { exact: true }).selectOption('undergraduate');
    await modal.getByLabel('具体学位名称（可选）').fill('BA');
    await modal.getByLabel('项目官网').fill('https://example.edu/qa');
    await capture(app, path.join(output, 'v020-project-form.png'));
    await modal.getByRole('button', { name: '保存项目', exact: true }).click();
    await modal.waitFor({ state: 'hidden' });
    let snapshot = await page.evaluate(() => window.desk.getSnapshot());
    const first = snapshot.projects[0];
    assert.equal(first.entryYear, 2038); assert.equal(first.entryMonth, 9);
    assert.equal(first.degreeLevel, 'undergraduate'); assert.equal(first.degreeName, 'BA');
    assert.equal(first.institution, 'University College London');
    report.assertions.push('custom entry year/month, degree level/name, city timezone and school alias save separately');
    await page.getByRole('button', { name: '我的学校', exact: true }).click();
    await page.locator('.school-programs button').first().click();
    await page.getByRole('button', { name: '复制为新目标', exact: true }).click();
    modal = page.getByRole('dialog', { name: '复制为新目标', exact: true });
    await modal.getByLabel('入学月份（可选）', { exact: true }).selectOption('1');
    await modal.getByRole('button', { name: '保存项目', exact: true }).click();
    await modal.waitFor({ state: 'hidden' });
    snapshot = await page.evaluate(() => window.desk.getSnapshot());
    assert.equal(snapshot.projects.length, 2); assert.equal(snapshot.requirements.length, 0);
    report.assertions.push('copy target creates an independent intake without copying requirements');
    await page.getByRole('button', { name: '添加事项', exact: true }).click();
    modal = page.getByRole('dialog', { name: '添加准备事项', exact: true });
    await modal.getByLabel('事项名称').fill('QA statement');
    await modal.getByLabel('具体要做什么').fill('Retain this unfinished draft across navigation.');
    await modal.getByRole('button', { name: '稍后继续', exact: true }).click();
    await page.getByRole('button', { name: '我的材料', exact: true }).click();
    await page.getByRole('button', { name: '我的学校', exact: true }).click();
    await page.getByRole('button', { name: '添加事项', exact: true }).click();
    modal = page.getByRole('dialog', { name: '添加准备事项', exact: true });
    await expect(modal.getByLabel('事项名称')).toHaveValue('QA statement');
    await modal.locator('summary', { hasText: '长度与数量限制' }).click();
    await modal.getByRole('button', { name: '添加限制', exact: true }).click();
    await expect(modal.getByLabel('限制数值')).toHaveValue('');
    await modal.getByRole('button', { name: '保存要求', exact: true }).click();
    assert.equal((await page.evaluate(() => window.desk.getSnapshot())).requirements.length, 0);
    await modal.getByLabel('限制数值').fill('120');
    await modal.getByRole('button', { name: '保存要求', exact: true }).click();
    await modal.waitFor({ state: 'hidden' });
    report.assertions.push('unfinished editor survives navigation; new limit is blank and incomplete values cannot save');
    await page.getByLabel('给自己留个备注').fill('Unsaved progress survives navigation');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '我的学校', exact: true }).click();
    await expect(page.getByLabel('给自己留个备注')).toHaveValue('Unsaved progress survives navigation');
    await page.locator('.detail-pane').getByRole('button', { name: '放弃修改', exact: true }).click();
    await expect(page.getByLabel('给自己留个备注')).toHaveValue('');
    await page.getByRole('button', { name: '正在等待', exact: true }).click();
    await page.locator('.detail-pane').getByRole('button', { name: '明天', exact: true }).click();
    const revisit = await page.getByLabel('哪天回访').inputValue();
    await page.getByRole('button', { name: '保存进度', exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.desk.getSnapshot()).progress[0].revisitOn)).toBe(revisit);
    report.assertions.push('progress drafts restore and discard explicitly; personal shortcut saves a concrete follow-up date');
    await page.evaluate(async projectId => {
      await window.desk.saveContact({ name: 'QA Referee', email: 'qa@example.test', note: '' });
      const s = await window.desk.getSnapshot();
      await window.desk.saveRecommendation({ projectId, contactId: s.contacts[0].id, stage: 'planned', revisitOn: '', note: '' });
    }, first.id);
    await page.getByRole('button', { name: '现在', exact: true }).click();
    await page.getByRole('button', { name: /记录联系结果/ }).click();
    modal = page.getByRole('dialog', { name: '记录推荐信进度', exact: true });
    await expect(modal).toBeVisible();
    await expect(modal.locator('select').first()).toHaveValue((await page.evaluate(() => window.desk.getSnapshot())).contacts[0].id);
    await modal.getByLabel('这个项目的进度').selectOption('received');
    await modal.getByRole('button', { name: '保存进度', exact: true }).click();
    await modal.waitFor({ state: 'hidden' });
    report.assertions.push('home recommendation action opens the exact project contact record');
    const file = path.join(data, 'qa-file.txt'); fs.writeFileSync(file, 'Version one.');
    await app.evaluate(({ dialog }, filename) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] }); }, file);
    const v1 = await page.evaluate(() => window.desk.importMaterial({ title: 'QA reusable statement' }));
    fs.writeFileSync(file, 'Version two, with a different revision.');
    const v2 = await page.evaluate(materialId => window.desk.importMaterial({ materialId }), v1.materialId);
    await page.locator('.detail-pane summary', { hasText: '从材料库选择版本' }).click();
    await page.getByLabel('搜索已有材料').fill('QA reusable');
    await page.getByLabel('选择材料', { exact: true }).selectOption(v1.materialId);
    await page.getByRole('button', { name: /^V1 · qa-file.txt/ }).click();
    await page.getByRole('button', { name: '保存进度', exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.desk.getSnapshot()).progress[0].selectedVersionId)).toBe(v1.id);
    await page.getByRole('button', { name: /^V2 · qa-file.txt/ }).click();
    await expect(page.getByRole('button', { name: /^V2 · qa-file.txt/ })).toHaveAttribute('aria-pressed', 'true');
    await page.locator('.detail-pane').getByRole('button', { name: '放弃修改', exact: true }).click();
    assert.equal((await page.evaluate(() => window.desk.getSnapshot())).progress[0].selectedVersionId, v1.id);
    report.assertions.push('search material then choose a version; discarding a replacement preserves the saved association');
    await page.getByLabel('给自己留个备注').fill('Close guard draft');
    await app.evaluate(({ dialog, BrowserWindow }) => { global.__closePrompts = 0; dialog.showMessageBoxSync = () => { global.__closePrompts++; return 0; }; BrowserWindow.getAllWindows()[0].close(); });
    assert.equal(await app.evaluate(() => global.__closePrompts), 1);
    await expect(page.getByLabel('给自己留个备注')).toHaveValue('Close guard draft');
    await page.locator('.detail-pane').getByRole('button', { name: '放弃修改', exact: true }).click();
    report.assertions.push('normal close asks about unsaved drafts; cancelling close preserves the window and input');
    const originalPath = (await page.evaluate(() => window.desk.getSnapshot())).dataPath;
    await page.getByLabel('给自己留个备注').fill('Original workspace draft only');
    const backup = path.join(data, 'draft-isolation.zip');
    await app.evaluate(({ dialog }, filename) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename }); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] }); }, backup);
    await page.evaluate(() => window.desk.createBackup());
    await page.evaluate(() => window.desk.restoreBackup());
    await expect.poll(() => page.evaluate(async () => (await window.desk.getSnapshot()).dataPath)).not.toBe(originalPath);
    await expect(page.getByLabel('给自己留个备注')).toHaveValue('');
    await page.evaluate(() => window.desk.switchWorkspace({ demo: false }));
    await expect(page.getByLabel('给自己留个备注')).toHaveValue('Original workspace draft only');
    await page.locator('.detail-pane').getByRole('button', { name: '放弃修改', exact: true }).click();
    report.assertions.push('a restored workspace has separate session drafts even when its stored workspace ID is identical');
    await capture(app, path.join(output, 'v020-material-versions.png'));
    assert.deepEqual(report.errors, []);
    report.status = 'passed';
  } catch (error) {
    report.status = 'failed'; report.failure = error.stack;
    if (app) { const page = await app.firstWindow().catch(() => null); if (page) { report.body = await page.locator('body').innerText().catch(() => ''); await capture(app, path.join(output, 'ux-failure.png')).catch(() => {}); } }
    throw error;
  } finally {
    if (app) { await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1; }).catch(() => {}); await app.close().catch(() => {}); }
    report.completedAt = new Date().toISOString(); fs.writeFileSync(path.join(output, 'ux-smoke.json'), JSON.stringify(report, null, 2));
  }
  console.log(JSON.stringify(report, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
