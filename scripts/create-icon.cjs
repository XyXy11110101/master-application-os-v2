const fs = require('node:fs');
const path = require('node:path');
const { createCanvas } = require('@napi-rs/canvas');
const dir = path.join(__dirname, '..', 'assets');
fs.mkdirSync(dir, { recursive: true });
const canvas = createCanvas(256, 256);
const ctx = canvas.getContext('2d');
ctx.fillStyle = '#236e66';
ctx.beginPath();
ctx.roundRect(0, 0, 256, 256, 54);
ctx.fill();
ctx.fillStyle = '#ffffff';
ctx.beginPath();
ctx.roundRect(63, 48, 130, 160, 14);
ctx.fill();
ctx.strokeStyle = '#236e66';
ctx.lineWidth = 9;
ctx.lineCap = 'round';
ctx.beginPath(); ctx.moveTo(88, 90); ctx.lineTo(96, 98); ctx.lineTo(109, 80); ctx.stroke();
ctx.beginPath(); ctx.moveTo(128, 90); ctx.lineTo(164, 90); ctx.stroke();
ctx.beginPath(); ctx.moveTo(88, 134); ctx.lineTo(96, 142); ctx.lineTo(109, 124); ctx.stroke();
ctx.beginPath(); ctx.moveTo(128, 134); ctx.lineTo(164, 134); ctx.stroke();
ctx.strokeStyle = '#b7d4cf';
ctx.beginPath(); ctx.moveTo(90, 176); ctx.lineTo(164, 176); ctx.stroke();
const png = canvas.toBuffer('image/png');
fs.writeFileSync(path.join(dir, 'icon.png'), png);
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18);
fs.writeFileSync(path.join(dir, 'icon.ico'), Buffer.concat([header, png]));
